"""Generate static Rust data from an aruljohn/Bible-kjv ZIP archive.

Usage: python3 tools/import_bible.py /path/to/source.zip
"""
import json
from pathlib import Path
import sys
import zipfile

root = Path(__file__).resolve().parents[1]
with zipfile.ZipFile(sys.argv[1]) as archive:
    prefix = next(n for n in archive.namelist() if n.endswith("/Books.json"))[:-10]
    names = json.loads(archive.read(prefix + "Books.json"))
    books = [json.loads(archive.read(prefix + name.replace(" ", "") + ".json")) for name in names]
    (root / "data" / "LICENSE").write_bytes(archive.read(prefix + "LICENSE"))

lines = ["// Generated by tools/import_bible.py. Source: https://github.com/aruljohn/Bible-kjv",
         "use crate::{Book, Chapter, Verse};", "#[rustfmt::skip]", "pub static BIBLE: &[Book] = &["]
for name, book in zip(names, books):
    lines.append(f"    Book {{ name: {json.dumps(name)}, chapters: &[")
    for chapter in book["chapters"]:
        lines.append(f'        Chapter {{ number: {int(chapter["chapter"])}, verses: &[')
        for verse in chapter["verses"]:
            # JSON escaping with literal Unicode is compatible with Rust strings.
            text = json.dumps(verse["text"], ensure_ascii=False)
            lines.append(f'            Verse {{ number: {int(verse["verse"])}, text: {text} }},')
        lines.append("        ] },")
    lines.append("    ] },")
lines.append("];\n")
(root / "src" / "bible.rs").write_text("\n".join(lines))
print(f"Generated {len(books)} books")
